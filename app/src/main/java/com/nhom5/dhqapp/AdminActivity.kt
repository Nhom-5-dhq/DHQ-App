
package com.nhom5.dhqapp

import android.content.Intent
import android.os.Bundle
import androidx.activity.ComponentActivity
import androidx.activity.compose.setContent
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.items
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp
import androidx.lifecycle.lifecycleScope
import com.nhom5.dhqapp.data.*
import kotlinx.coroutines.launch
import kotlinx.coroutines.flow.first
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import kotlin.random.Random

@OptIn(ExperimentalMaterial3Api::class)
class AdminActivity : ComponentActivity() {

    private lateinit var db: AppDatabase
    private lateinit var session: SessionManager

    private fun randomPassword(): String {

        val chars =
            "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789"

        return (1..8)
            .map { chars[Random.nextInt(chars.length)] }
            .joinToString("")
    }

    private fun date(value: Long): String {

        if (value <= 0) return "Chưa ghi nhận"

        return SimpleDateFormat(
            "dd/MM/yyyy HH:mm",
            Locale.getDefault()
        ).format(Date(value))
    }

    override fun onCreate(savedInstanceState: Bundle?) {

        super.onCreate(savedInstanceState)

        db = AppDatabase.getDatabase(this)
        session = SessionManager(this)

        setContent {

            var tab by remember { mutableIntStateOf(0) }

            var users by remember {
                mutableStateOf(emptyList<User>())
            }

            var requests by remember {
                mutableStateOf(emptyList<PasswordResetRequest>())
            }

            var logs by remember {
                mutableStateOf(emptyList<PasswordChangeLog>())
            }

            var generated by remember {
                mutableStateOf<String?>(null)
            }

            var ready by remember {
                mutableStateOf(false)
            }

            var authorized by remember {
                mutableStateOf(false)
            }

            // Tải dữ liệu từ Room
            suspend fun reload() {

                users = db.userDao().getAllCustomers()

                requests = db.passwordResetDao().getPending()

                logs = db.passwordChangeLogDao().getAll()
            }

            // Kiểm tra quyền Admin trước khi hiển thị
            LaunchedEffect(Unit) {

                val userId = session.loggedInUserId.first()

                val currentUser =
                    if (userId != -1) db.userDao().findById(userId)
                    else null

                if (currentUser?.role == "admin" &&
                    currentUser.isActive
                ) {

                    authorized = true
                    reload()

                } else {

                    session.logout()

                    startActivity(
                        Intent(
                            this@AdminActivity,
                            WelcomeActivity::class.java
                        ).apply {
                            flags =
                                Intent.FLAG_ACTIVITY_NEW_TASK or
                                        Intent.FLAG_ACTIVITY_CLEAR_TASK
                        }
                    )

                    finish()
                }

                ready = true
            }

            MaterialTheme {

                if (!ready) {

                    Box(
                        modifier = Modifier.fillMaxSize(),
                        contentAlignment = Alignment.Center
                    ) {
                        CircularProgressIndicator()
                    }

                } else if (authorized) {

                    Scaffold(

                        topBar = {

                            TopAppBar(

                                title = {
                                    Text("Quản trị DHQ-App")
                                },

                                actions = {

                                    TextButton(

                                        onClick = {

                                            lifecycleScope.launch {

                                                session.logout()

                                                startActivity(
                                                    Intent(
                                                        this@AdminActivity,
                                                        WelcomeActivity::class.java
                                                    ).apply {
                                                        flags =
                                                            Intent.FLAG_ACTIVITY_NEW_TASK or
                                                                    Intent.FLAG_ACTIVITY_CLEAR_TASK
                                                    }
                                                )

                                                finish()
                                            }
                                        }

                                    ) {
                                        Text("Đăng xuất")
                                    }
                                }
                            )
                        }

                    ) { padding ->

                        Column(

                            modifier = Modifier
                                .padding(padding)
                                .fillMaxSize()
                                .padding(12.dp)

                        ) {

                            Text(
                                "Xin chào, Quản trị viên",
                                style = MaterialTheme.typography.titleLarge
                            )

                            Spacer(Modifier.height(12.dp))

                            TabRow(selectedTabIndex = tab) {

                                listOf(
                                    "Yêu cầu",
                                    "Tài khoản",
                                    "Lịch sử"
                                ).forEachIndexed { index, title ->

                                    Tab(
                                        selected = tab == index,
                                        onClick = { tab = index },
                                        text = { Text(title) }
                                    )
                                }
                            }

                            Spacer(Modifier.height(12.dp))

                            when (tab) {

                                // TAB 1: YÊU CẦU QUÊN MẬT KHẨU
                                0 -> {

                                    LazyColumn(
                                        verticalArrangement =
                                            Arrangement.spacedBy(8.dp)
                                    ) {

                                        if (requests.isEmpty()) {

                                            item {
                                                Text(
                                                    "Không có yêu cầu đang chờ duyệt."
                                                )
                                            }
                                        }

                                        items(
                                            requests,
                                            key = { it.id }
                                        ) { req ->

                                            val user = users.firstOrNull {
                                                it.id == req.userId
                                            }

                                            Card(
                                                modifier =
                                                    Modifier.fillMaxWidth()
                                            ) {

                                                Column(
                                                    Modifier.padding(12.dp)
                                                ) {

                                                    Text(
                                                        user?.name
                                                            ?: "Tài khoản #${req.userId}",
                                                        style = MaterialTheme
                                                            .typography.titleMedium
                                                    )

                                                    Text(user?.email.orEmpty())

                                                    Text(
                                                        "Ngày gửi: ${date(req.requestedAt)}"
                                                    )

                                                    Text(
                                                        "Trạng thái: ${req.status}"
                                                    )

                                                    Spacer(
                                                        Modifier.height(8.dp)
                                                    )

                                                    Row(
                                                        horizontalArrangement =
                                                            Arrangement.spacedBy(8.dp)
                                                    ) {

                                                        Button(

                                                            onClick = {

                                                                lifecycleScope.launch {

                                                                    val target =
                                                                        db.userDao()
                                                                            .findById(req.userId)

                                                                    if (
                                                                        target != null &&
                                                                        target.role == "user"
                                                                    ) {

                                                                        val pass =
                                                                            randomPassword()

                                                                        val now =
                                                                            System.currentTimeMillis()

                                                                        val updated =
                                                                            db.userDao()
                                                                                .updatePassword(
                                                                                    target.id,
                                                                                    pass,
                                                                                    now,
                                                                                    "admin"
                                                                                )

                                                                        if (updated > 0) {

                                                                            val processed =
                                                                                db.passwordResetDao()
                                                                                    .process(
                                                                                        req.id,
                                                                                        "APPROVED",
                                                                                        pass,
                                                                                        now,
                                                                                        "admin"
                                                                                    )

                                                                            if (processed > 0) {

                                                                                db.passwordChangeLogDao()
                                                                                    .insert(
                                                                                        PasswordChangeLog(
                                                                                            userId = target.id,
                                                                                            action = "RESET_APPROVED",
                                                                                            changedBy = "admin",
                                                                                            createdAt = now,
                                                                                            note = "Admin duyệt yêu cầu lấy lại mật khẩu"
                                                                                        )
                                                                                    )

                                                                                generated =
                                                                                    "${target.email}\nMật khẩu tạm: $pass"
                                                                            }
                                                                        }
                                                                    }

                                                                    reload()
                                                                }
                                                            }

                                                        ) {
                                                            Text("Duyệt")
                                                        }

                                                        OutlinedButton(

                                                            onClick = {

                                                                lifecycleScope.launch {

                                                                    val now =
                                                                        System.currentTimeMillis()

                                                                    val processed =
                                                                        db.passwordResetDao()
                                                                            .process(
                                                                                req.id,
                                                                                "REJECTED",
                                                                                null,
                                                                                now,
                                                                                "admin"
                                                                            )

                                                                    if (processed > 0) {

                                                                        db.passwordChangeLogDao()
                                                                            .insert(
                                                                                PasswordChangeLog(
                                                                                    userId = req.userId,
                                                                                    action = "RESET_REJECTED",
                                                                                    changedBy = "admin",
                                                                                    createdAt = now,
                                                                                    note = "Admin từ chối yêu cầu"
                                                                                )
                                                                            )
                                                                    }

                                                                    reload()
                                                                }
                                                            }

                                                        ) {
                                                            Text("Từ chối")
                                                        }
                                                    }
                                                }
                                            }
                                        }
                                    }
                                }

                                // TAB 2: QUẢN LÝ TÀI KHOẢN
                                1 -> {

                                    LazyColumn(
                                        verticalArrangement =
                                            Arrangement.spacedBy(8.dp)
                                    ) {

                                        if (users.isEmpty()) {

                                            item {
                                                Text("Chưa có người dùng.")
                                            }
                                        }

                                        items(
                                            users,
                                            key = { it.id }
                                        ) { user ->

                                            Card(
                                                modifier =
                                                    Modifier.fillMaxWidth()
                                            ) {

                                                Column(
                                                    Modifier.padding(12.dp)
                                                ) {

                                                    Text(
                                                        user.name,
                                                        style = MaterialTheme
                                                            .typography.titleMedium
                                                    )

                                                    Text("Email: ${user.email}")

                                                    Text(
                                                        "Điện thoại: ${
                                                            user.phone.ifBlank {
                                                                "Chưa cập nhật"
                                                            }
                                                        }"
                                                    )

                                                    Text(
                                                        if (user.isActive)
                                                            "Trạng thái: Đang hoạt động"
                                                        else
                                                            "Trạng thái: Đã khóa"
                                                    )

                                                    Text(
                                                        "Đổi mật khẩu: ${
                                                            date(user.lastPasswordChangedAt)
                                                        }"
                                                    )

                                                    Text(
                                                        "Người đổi: ${user.passwordChangedBy}"
                                                    )

                                                    Spacer(
                                                        Modifier.height(8.dp)
                                                    )

                                                    Row(
                                                        horizontalArrangement =
                                                            Arrangement.spacedBy(8.dp)
                                                    ) {

                                                        OutlinedButton(

                                                            onClick = {

                                                                lifecycleScope.launch {

                                                                    db.userDao()
                                                                        .setActive(
                                                                            user.id,
                                                                            !user.isActive
                                                                        )

                                                                    reload()
                                                                }
                                                            }

                                                        ) {

                                                            Text(
                                                                if (user.isActive)
                                                                    "Khóa"
                                                                else
                                                                    "Mở khóa"
                                                            )
                                                        }

                                                        Button(

                                                            onClick = {

                                                                lifecycleScope.launch {

                                                                    val pass =
                                                                        randomPassword()

                                                                    val now =
                                                                        System.currentTimeMillis()

                                                                    val updated =
                                                                        db.userDao()
                                                                            .updatePassword(
                                                                                user.id,
                                                                                pass,
                                                                                now,
                                                                                "admin"
                                                                            )

                                                                    if (updated > 0) {

                                                                        db.passwordChangeLogDao()
                                                                            .insert(
                                                                                PasswordChangeLog(
                                                                                    userId = user.id,
                                                                                    action = "ADMIN_RESET",
                                                                                    changedBy = "admin",
                                                                                    createdAt = now,
                                                                                    note = "Admin đặt lại mật khẩu thủ công"
                                                                                )
                                                                            )

                                                                        generated =
                                                                            "${user.email}\nMật khẩu mới: $pass"
                                                                    }

                                                                    reload()
                                                                }
                                                            }

                                                        ) {
                                                            Text("Đặt lại mật khẩu")
                                                        }
                                                    }
                                                }
                                            }
                                        }
                                    }
                                }

                                // TAB 3: LỊCH SỬ MẬT KHẨU
                                else -> {

                                    LazyColumn {

                                        if (logs.isEmpty()) {

                                            item {
                                                Text("Chưa có lịch sử.")
                                            }
                                        }

                                        items(
                                            logs,
                                            key = { it.id }
                                        ) { log ->

                                            val user = users.firstOrNull {
                                                it.id == log.userId
                                            }

                                            ListItem(

                                                headlineContent = {
                                                    Text(log.action)
                                                },

                                                supportingContent = {

                                                    Text(
                                                        """
                                                        Tài khoản: ${user?.email ?: "User #${log.userId}"}
                                                        Thời gian: ${date(log.createdAt)}
                                                        Người thực hiện: ${log.changedBy}
                                                        Ghi chú: ${log.note}
                                                        """.trimIndent()
                                                    )
                                                }
                                            )

                                            HorizontalDivider()
                                        }
                                    }
                                }
                            }
                        }
                    }

                    // Hiển thị mật khẩu tạm sau khi Admin tạo
                    generated?.let { password ->

                        AlertDialog(

                            onDismissRequest = {
                                generated = null
                            },

                            title = {
                                Text("Mật khẩu đã tạo")
                            },

                            text = {
                                Text(password)
                            },

                            confirmButton = {

                                TextButton(
                                    onClick = {
                                        generated = null
                                    }
                                ) {
                                    Text("Đã hiểu")
                                }
                            }
                        )
                    }
                }
            }
        }
    }
}
